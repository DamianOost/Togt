export type EnZaMessageKey = keyof typeof EN_ZA_MESSAGES;
export type EnZaInterpolation = Readonly<Record<string, string | number>>;

const PLACEHOLDER = /\{([A-Za-z][A-Za-z0-9]*)\}/g;

export function translateEnZa(
  key: EnZaMessageKey,
  interpolation: EnZaInterpolation = {},
): string {
  const template = EN_ZA_MESSAGES[key];
  return template.replace(PLACEHOLDER, (_match, placeholder: string) => {
    const value = interpolation[placeholder];
    if (value === undefined) {
      throw new Error(`Missing en-ZA interpolation value: ${placeholder}`);
    }
    return String(value);
  });
}

const ZAR_FORMATTER = new Intl.NumberFormat(SOURCE_LOCALE, {
  style: 'currency',
  currency: 'ZAR',
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

export function formatZarEnZa(amount: number): string {
  if (!Number.isFinite(amount)) {
    throw new TypeError('A finite ZAR amount is required');
  }
  return ZAR_FORMATTER.format(amount);
}
